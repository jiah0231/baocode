HANDLE Spawn(const std::wstring& args) {
  std::wstring command=L"\""+ExecutablePath()+L"\" "+args;
  STARTUPINFOW startup{}; startup.cb=sizeof(startup); PROCESS_INFORMATION pi{};
  Require(CreateProcessW(nullptr,command.data(),nullptr,nullptr,FALSE,0,nullptr,nullptr,&startup,&pi)!=0,
      "Cannot start owned diagnostic helper");
  CloseHandle(pi.hThread); return pi.hProcess;
}
