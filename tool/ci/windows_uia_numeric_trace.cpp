struct BrowserIdentity::Impl {
  DWORD pid=0;ULONGLONG created=0;std::wstring exact_path;Handle process;
  Impl(const wchar_t* expected_pid,const wchar_t* expected_created,const wchar_t* path)
      : pid(ToUlong(expected_pid)),created(ToU64(expected_created)),exact_path(path) {
    Require(Disposable() && !exact_path.empty(),"Missing exact launched browser identity");
    process.value=OpenProcess(PROCESS_QUERY_LIMITED_INFORMATION|SYNCHRONIZE,FALSE,pid);
    Require(process.value && Current(),"Launched browser PID, creation time or exact executable differs");
    std::printf("UIA_TRACE_BROWSER_IDENTITY|pid=%lu|creationFileTime=%llu|exactPathVerified=1|heldHandle=1\n",pid,created);
  }
  bool Current() const {
    if(!process.value || WaitForSingleObject(process.value,0)!=WAIT_TIMEOUT || GetProcessId(process.value)!=pid) return false;
    FILETIME creation{},exit{},kernel{},user{};
    if(!GetProcessTimes(process.value,&creation,&exit,&kernel,&user)) return false;
    const ULONGLONG actual=(static_cast<ULONGLONG>(creation.dwHighDateTime)<<32)|creation.dwLowDateTime;
    wchar_t image[32768]{};DWORD length=32768;
    return actual==created && QueryFullProcessImageNameW(process.value,0,image,&length) &&
        _wcsicmp(image,exact_path.c_str())==0;
  }
};
BrowserIdentity::BrowserIdentity(const wchar_t* pid,const wchar_t* created,const wchar_t* path)
    : impl_(std::make_unique<Impl>(pid,created,path)) {}
BrowserIdentity::~BrowserIdentity() = default;
bool BrowserIdentity::Matches(HWND source) const {
  DWORD pid=0;
  return source && GetWindowThreadProcessId(source,&pid) && pid==impl_->pid && impl_->Current();
}

struct CaptureTrace::Impl {
  HWND source=nullptr;DWORD edge=0,thread=0; Handle process;FILETIME created{};
  std::unique_ptr<Session> session; bool finished=false;
  std::wstring receipt_path;GUID session_id{};const BrowserIdentity& launched;
  Impl(HWND window,const wchar_t* receipt,const wchar_t* identity,const BrowserIdentity& expected)
      : source(window),receipt_path(receipt),session_id(ParseGuid(identity)),launched(expected) {
    Require(Disposable(),"Scoped trace requires explicit disposable CI environment");
    const ULONGLONG setup=GetTickCount64();
    VerifyReceipt(receipt,session_id); const Audit audit=AuditSchema();
    Require(launched.Matches(source),"Source is not the exact launched Edge instance");
    thread=GetWindowThreadProcessId(source,&edge);
    Require(thread && edge && edge!=GetCurrentProcessId() && GetForegroundWindow()==source &&
        GetAncestor(source,GA_ROOT)==source,"Invalid verified source for scoped trace");
    process.value=OpenProcess(PROCESS_QUERY_LIMITED_INFORMATION|SYNCHRONIZE,FALSE,edge);
    FILETIME end{},kernel{},user{};
    Require(process.value && GetProcessTimes(process.value,&created,&end,&kernel,&user) &&
        WaitForSingleObject(process.value,0)==WAIT_TIMEOUT,"Cannot pin verified browser process");
    session=std::make_unique<Session>(session_id,kUia,std::vector<DWORD>{GetCurrentProcessId(),edge},
        std::vector<USHORT>{521,522,544,545,546,547},false,audit);
    LARGE_INTEGER frequency{};Require(QueryPerformanceFrequency(&frequency)!=0,"QPC frequency unavailable");
    std::printf("UIA_TRACE_CAPTURE_READY|setupMs=%llu|clientPID=%lu|browserPID=%lu|qpcFrequency=%lld|queueCapacity=%zu|rawFile=0\n",
        GetTickCount64()-setup,GetCurrentProcessId(),edge,frequency.QuadPart,kCapacity);
  }
  bool SourceCurrent() {
    DWORD pid=0; const DWORD tid=GetWindowThreadProcessId(source,&pid);
    return launched.Matches(source) && pid==edge && tid==thread && GetForegroundWindow()==source &&
        WaitForSingleObject(process.value,0)==WAIT_TIMEOUT;
  }
  bool Finish() {
    if(finished) return false; finished=true;
    auto& data=session->data();
    const bool source_ok=SourceCurrent();bool valid=session->Stop()&&source_ok;
    try {
      Require(GetModuleHandleW(L"UIAutomationCore.dll")!=nullptr,"No loaded UIA client module to verify");
      VerifyReceipt(receipt_path.c_str(),session_id);
    } catch(...) { valid=false;std::puts("UIA_TRACE_RUNTIME_IDENTITY|INVALID"); }
    const LONGLONG start=data.capture_start.load(),end=data.capture_end.load();
    if(!valid || !start || end<start) {
      std::puts("UIA_TRACE_CAPTURE|INVALID|numericEventsSuppressed=1");return false;
    }
    const auto attributed_peer = [&](const NumericEvent& e) {
      if(e.id==544 || e.id==547) return true; // Local cross-machine flag already checked.
      if(e.id!=545 && e.id!=546) return false;
      for(size_t j=0;j<data.count;++j) {
        const auto& peer=data.events[j];
        if((peer.id==544 || peer.id==547) && peer.pid==e.values[1] && peer.values[1]==e.pid &&
            peer.values[0]==e.values[0] && peer.qpc>=start && peer.qpc<=end) return true;
      }
      return false;
    };
    unsigned unpaired_dispatch=0,unpaired_server=0,outside_window=0,printed=0;
    for(size_t i=0;i<data.count;++i) {
      const auto& e=data.events[i];
      if(e.qpc<start || e.qpc>end) { ++outside_window;continue; }
      if((e.id==545 || e.id==546) && !attributed_peer(e)) { ++unpaired_server;continue; }
      if(e.id==521 || e.id==522) {
        bool associated=false;
        for(size_t j=0;j<data.count;++j) {
          const auto& peer=data.events[j];
          if(attributed_peer(peer) && peer.pid==e.pid && peer.values[0]==e.values[2] &&
              peer.qpc>=start && peer.qpc<=end) associated=true;
        }
        if(!associated) { ++unpaired_dispatch;continue; }
      }
      const auto* schema=uia_numeric_schema::find(e.id);
      std::printf("UIA_NUMERIC_EVENT|id=%u|version=0|pid=%lu|tid=%lu|qpc=%lld",e.id,e.pid,e.tid,e.qpc);
      for(size_t f=0;f<schema->field_count;++f) {
        // Field labels are exclusively the reviewed compile-time schema.
        if(schema->fields[f].kind==uia_numeric_schema::Kind::HexInt32)
          std::printf("|%ls=0x%08X",schema->fields[f].name.data(),e.values[f]);
        else std::printf("|%ls=%u",schema->fields[f].name.data(),e.values[f]);
      }
      std::puts("");++printed;
    }
    std::printf("UIA_TRACE_CAPTURE|startQpc=%lld|endQpc=%lld|events=%u|nonPairEvents=%u|unattributedDispatch=%u|unattributedServer=%u|crossMachineEvents=%u|outsideWindow=%u|infrastructureHeaders=%u|PASS\n",
        start,end,printed,data.non_pair,unpaired_dispatch,unpaired_server,data.cross_machine,outside_window,data.infrastructure);
    return true;
  }
};
CaptureTrace::CaptureTrace(HWND source,const wchar_t* receipt,const wchar_t* session,const BrowserIdentity& browser)
    : impl_(std::make_unique<Impl>(source,receipt,session,browser)) {}
CaptureTrace::~CaptureTrace() = default;
void CaptureTrace::MarkCaptureStart() {
  Require(impl_->SourceCurrent(),"Source changed before scoped capture");impl_->session->data().capture_start.store(Qpc());
}
void CaptureTrace::MarkCaptureEnd() { impl_->session->data().capture_end.store(Qpc()); }
bool CaptureTrace::Finish() { return impl_->Finish(); }
std::optional<int> ToolMode(int argc,wchar_t** argv) {
  if(argc<2) return std::nullopt;
  const std::wstring mode=argv[1];
  if(mode!=L"--verify-scoped-timing" && mode!=L"--cleanup-scoped-timing" &&
      mode!=L"--uia-numeric-probe-child" && mode!=L"--uia-numeric-watchdog") return std::nullopt;
  try {
    Require(Disposable(),"Diagnostic tool mode requires explicit disposable CI environment");
    if(mode==L"--cleanup-scoped-timing") {
      Require(argc==3,"Invalid cleanup arguments");const ULONG error=Cleanup(ParseGuid(argv[2]));
      std::printf("UIA_OWN_SESSION_CLEANUP|result=%lu\n",error);return error==ERROR_SUCCESS?0:1;
    }
    if(mode==L"--uia-numeric-watchdog") {
      Require(argc==5,"Invalid watchdog arguments");return Watchdog(ParseGuid(argv[2]),ToUlong(argv[3]),ToU64(argv[4]));
    }
    if(mode==L"--uia-numeric-probe-child") {
      Require(argc==4,"Invalid probe arguments");return ProbeChild(ParseGuid(argv[2]),ParseGuid(argv[3]));
    }
    Require(argc==5,"Invalid verification arguments");
    AuditSchema();Identity();VerifyFilters(ParseGuid(argv[3]));WriteReceipt(argv[2],ParseGuid(argv[4]));
    std::puts("UIA_TIMING_SELFTEST|PASS|uiaSessionStarted=0|rawTraceFile=0");return 0;
  } catch(const std::exception& e) { std::fprintf(stderr,"UIA_TRACE_DIAGNOSTIC_FAILED|%s\n",e.what());return 1; }
}
