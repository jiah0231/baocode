HANDLE NewEvent(const std::wstring& name, bool manual = true) {
  HANDLE h = CreateEventW(nullptr,manual ? TRUE : FALSE,FALSE,name.c_str());
  const DWORD error = GetLastError();
  if (!h || error == ERROR_ALREADY_EXISTS) {
    if (h) CloseHandle(h);
    throw std::runtime_error("Cannot create uniquely owned diagnostic synchronization event");
  }
  return h;
}
