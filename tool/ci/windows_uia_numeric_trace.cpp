ULONG Cleanup(const GUID& id) {
  Properties query(id); const auto name=SessionName(id);
  ULONG error=ControlTraceW(0,name.c_str(),&query.p,EVENT_TRACE_CONTROL_QUERY);
  if (error==ERROR_WMI_INSTANCE_NOT_FOUND) return ERROR_SUCCESS;
  if (error!=ERROR_SUCCESS) return error;
  if (!SameGuid(query.p.Wnode.Guid,id)) return ERROR_ACCESS_DENIED;
  return ControlTraceW(0,name.c_str(),&query.p,EVENT_TRACE_CONTROL_STOP);
}
