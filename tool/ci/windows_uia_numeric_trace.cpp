std::wstring_view MetadataString(const std::vector<unsigned char>& bytes, ULONG offset) {
  Require(offset && offset%sizeof(wchar_t)==0 && offset<bytes.size(),"Invalid metadata string offset");
  const wchar_t* p=reinterpret_cast<const wchar_t*>(bytes.data()+offset);
  const size_t room=(bytes.size()-offset)/sizeof(wchar_t);
  size_t n=0; while(n<room && p[n]) ++n;
  Require(n<room,"Unterminated metadata string"); return {p,n};
}
Audit AuditSchema() {
  const ULONGLONG started=GetTickCount64();
  GUID provider=kUia; ULONG size=0;
  Require(TdhEnumerateManifestProviderEvents(&provider,nullptr,&size)==ERROR_INSUFFICIENT_BUFFER &&
      size>=sizeof(PROVIDER_EVENT_INFO) && size<=kMetadataLimit,"Cannot enumerate bounded UIA manifest metadata");
  std::vector<unsigned char> bytes(size);
  Require(TdhEnumerateManifestProviderEvents(&provider,reinterpret_cast<PROVIDER_EVENT_INFO*>(bytes.data()),&size)==ERROR_SUCCESS,
      "Cannot read UIA manifest metadata");
  const auto* list=reinterpret_cast<const PROVIDER_EVENT_INFO*>(bytes.data());
  Require(offsetof(PROVIDER_EVENT_INFO,EventDescriptorsArray)+
      static_cast<size_t>(list->NumberOfEvents)*sizeof(EVENT_DESCRIPTOR)<=bytes.size(),"Invalid event descriptor array");
  Audit audit; std::array<unsigned,6> seen{};
  for (ULONG e=0;e<list->NumberOfEvents;++e) {
    const auto descriptor=list->EventDescriptorsArray[e];
    const auto* schema=uia_numeric_schema::find(descriptor.Id);
    if (!schema) continue;
    const size_t slot=static_cast<size_t>(schema-uia_numeric_schema::kSchemas);
    Require(descriptor.Version==0 && ++seen[slot]==1,"Unknown/duplicate version of allowed UIA event");
    ULONG needed=0; EVENT_DESCRIPTOR requested=descriptor;
    Require(TdhGetManifestEventInformation(&provider,&requested,nullptr,&needed)==ERROR_INSUFFICIENT_BUFFER &&
        needed>=sizeof(TRACE_EVENT_INFO) && needed<=kMetadataLimit,"Cannot size reviewed event metadata");
    std::vector<unsigned char> meta(needed);
    Require(TdhGetManifestEventInformation(&provider,&requested,reinterpret_cast<TRACE_EVENT_INFO*>(meta.data()),&needed)==ERROR_SUCCESS,
        "Cannot read reviewed event metadata");
    const auto* info=reinterpret_cast<const TRACE_EVENT_INFO*>(meta.data());
    Require(SameGuid(info->ProviderGuid,kUia) && info->DecodingSource==DecodingSourceXMLFile &&
        std::memcmp(&info->EventDescriptor,&descriptor,sizeof(descriptor))==0 &&
        info->PropertyCount==schema->field_count && info->TopLevelPropertyCount==schema->field_count &&
        offsetof(TRACE_EVENT_INFO,EventPropertyInfoArray)+schema->field_count*sizeof(EVENT_PROPERTY_INFO)<=meta.size(),
        "UIA event descriptor/property count is not exact reviewed schema");
    std::array<uia_numeric_schema::FieldMetadata,6> fields{};
    for (size_t f=0;f<schema->field_count;++f) {
      const auto& prop=info->EventPropertyInfoArray[f];
      // No union interpretation until all structure/array/custom flags rejected.
      Require(prop.Flags==0,"Structured, array or unknown metadata flag rejected");
      Require(uia_numeric_schema::matches_tdh_type(schema->fields[f].kind,
          prop.nonStructType.InType,prop.nonStructType.OutType) && prop.nonStructType.MapNameOffset==0,
          "UIA input/output type or map differs from reviewed scalar");
      fields[f]={MetadataString(meta,prop.NameOffset),schema->fields[f].kind,
          static_cast<uint32_t>(prop.Flags),prop.count,prop.length};
    }
    Require(uia_numeric_schema::validate_metadata(*schema,fields.data(),schema->field_count),
        "UIA field names/order/scalar metadata do not exactly match review");
    audit.descriptors[slot]=descriptor; audit.keywords|=descriptor.Keyword;
    audit.level=std::max(audit.level,descriptor.Level);
    std::printf("UIA_SCHEMA_AUDIT|event=%u|version=0|fields=%zu|bytes=%zu|PASS\n",
        schema->id,schema->field_count,schema->bytes);
  }
  for (unsigned n:seen) Require(n==1,"A reviewed event is missing");
  std::printf("UIA_SCHEMA_AUDIT_COMPLETE|elapsedMs=%llu|uiaSessionStarted=0\n",GetTickCount64()-started);
  return audit;
}
std::array<unsigned char,32> HashFile(const std::wstring& path) {
  Handle file(CreateFileW(path.c_str(),GENERIC_READ,FILE_SHARE_READ|FILE_SHARE_DELETE,nullptr,OPEN_EXISTING,FILE_ATTRIBUTE_NORMAL,nullptr));
  Require(file.value!=INVALID_HANDLE_VALUE,"Cannot open diagnostic identity file");
  LARGE_INTEGER length{};
  Require(GetFileSizeEx(file.value,&length) && length.QuadPart>0 && length.QuadPart<=128*1024*1024,
      "Diagnostic identity file outside bounded size");
  BCRYPT_ALG_HANDLE algorithm=nullptr; BCRYPT_HASH_HANDLE hash=nullptr;
  Require(BCryptOpenAlgorithmProvider(&algorithm,BCRYPT_SHA256_ALGORITHM,nullptr,0)>=0,"SHA256 unavailable");
  std::array<unsigned char,32> digest{};
  try {
    Require(BCryptCreateHash(algorithm,&hash,nullptr,0,nullptr,0,0)>=0,"Cannot create SHA256 context");
    std::array<unsigned char,65536> block{};
    for (;;) {
      DWORD read=0; Require(ReadFile(file.value,block.data(),static_cast<DWORD>(block.size()),&read,nullptr)!=0,"Identity file read failed");
      if (!read) break;
      Require(BCryptHashData(hash,block.data(),read,0)>=0,"SHA256 update failed");
    }
    Require(BCryptFinishHash(hash,digest.data(),static_cast<ULONG>(digest.size()),0)>=0,"SHA256 finish failed");
  } catch (...) { if(hash) BCryptDestroyHash(hash); BCryptCloseAlgorithmProvider(algorithm,0); throw; }
  BCryptDestroyHash(hash); BCryptCloseAlgorithmProvider(algorithm,0); return digest;
}
